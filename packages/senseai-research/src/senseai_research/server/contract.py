"""The contract a front end (Studio, the viewer) codes against: the HTTP routes, which are also
in the OpenAPI document at ``/api/research/openapi.json``, and the Server-Sent Events a chat
turn streams, which OpenAPI cannot describe.

``docs/API.md`` is generated from this module (``senseai-research api-doc``); a test fails when
the code emits an event that is not listed here.
"""

from __future__ import annotations

from typing import Any

# event name -> (payload fields, what a front end does with it)
EVENTS: dict[str, tuple[str, str]] = {
    "text_delta": ("`text`", "Append to the assistant's reply."),
    "thinking_summary": (
        "`text`",
        "A summary of the assistant's reasoning; show folded away, never as the answer.",
    ),
    "tool_call": (
        "`id`, `name`, `label`, `kind` (read, compute or write)",
        "Show `label` as a chip (plain language, never the raw input).",
    ),
    "tool_result_summary": (
        "`id`, `ok`, `summary`, `refs`",
        "Mark the chip done or failed. `refs` may hold `claim_id`, `impact_id`, "
        "`experiment_id`, `source_id`, `doi`, `section`, `text`, `context_before`, "
        "`context_after`, `pending_action_id`: open the matching panel.",
    ),
    "pending_action": (
        "`action`: `id`, `kind`, `status`, `card` {`title`, `summary`, `rows` [{`label`, "
        "`before`, `after`}], `quote`, `diff`, `note`}, `error`",
        "Show an Approve / Reject card with a required rationale; post it to "
        "`/api/research/actions/{action.id}/approve` (or `/reject`).",
    ),
    "job_progress": (
        "`job_id`, `frac`, `message` (and the bench event fields)",
        "Show experiment progress.",
    ),
    "error": (
        "`message`, optional `code` (refusal, max_tokens, unverified_number or no_api_key), "
        "optional `numbers`",
        "Show `message`. `unverified_number` flags numbers in the reply that no stored "
        "record supports.",
    ),
    "done": (
        "`stop` (end_turn, pending_action, refusal, max_tokens, error or step_limit), "
        "`pending` [action ids], `usage`",
        "The turn is over; enable the composer again.",
    ),
}

HEADERS = (
    (
        "X-SenseAI-User",
        "The signed-in person's name. Required on every write; stored on every Approval.",
    ),
    (
        "X-SenseAI-Proxy-Token",
        "Equal to `RESEARCH_PROXY_TOKEN`. Required unless the caller is "
        "on the research server's own machine.",
    ),
)


def routes(app: Any) -> list[tuple[str, str, str]]:
    """``(methods, path, first docstring line)`` for every documented route."""
    out: list[tuple[str, str, str]] = []
    for r in app.routes:
        path = getattr(r, "path", "")
        if not path.startswith("/api/research") or not getattr(r, "include_in_schema", True):
            continue
        methods = ",".join(sorted(m for m in getattr(r, "methods", set()) if m != "HEAD"))
        doc = (getattr(r, "endpoint", None).__doc__ or "").strip().splitlines()
        out.append((methods, path, doc[0] if doc else ""))
    return sorted(out, key=lambda x: (x[1], x[0]))


def render_doc(app: Any) -> str:
    """``docs/API.md``."""
    lines = [
        "# Research API (what Studio and the viewer call)",
        "",
        "<!-- Generated by `senseai-research api-doc` from"
        " `src/senseai_research/server/contract.py`. Do not edit by hand. -->",
        "",
        "senseai-research is the source of truth for the backend; front ends (Studio, the",
        "viewer) reach it through their own proxy at `/api/research/*`. The full request and",
        "response schemas are in the OpenAPI document at `/api/research/openapi.json`.",
        "",
        "## Headers the front end's proxy sends",
        "",
        "| Header | Meaning |",
        "|---|---|",
        *(f"| `{h}` | {m} |" for h, m in HEADERS),
        "",
        '`GET /healthz` is open and answers only `{"ok": true}`.',
        "",
        "## Routes",
        "",
        "| Method | Path | |",
        "|---|---|---|",
        *(f"| {m} | `{p}` | {d} |" for m, p, d in routes(app)),
        "",
        "## Chat events",
        "",
        '`POST /api/research/conversations/{id}/messages` with `{"text": ..., "focus":'
        ' {"claim_id" | "library_path": ...}}` answers with Server-Sent Events. Each event'
        " has a name and a JSON `data` line.",
        "",
        "| Event | Data | What to do |",
        "|---|---|---|",
        *(f"| `{name}` | {fields} | {use} |" for name, (fields, use) in EVENTS.items()),
        "",
    ]
    return "\n".join(lines)


__all__ = ["EVENTS", "HEADERS", "render_doc", "routes"]
